"""
BST — Contact-Matter Taxonomy Test

Purpose
-------
Classify matter-like periodic contact attractors generated by stable
wave-cluster interactions.

Corrected version:
- robust recurrence estimation;
- signed recurrence + absolute recurrence strength;
- phase orientation kept as an interpretable feature;
- safe bounded loop/tunnel scores;
- log-scaled intensity features;
- stabilized clustering;
- explicit weak/strong taxonomy verdicts.

Outputs
-------
results/research_final/contact_matter_taxonomy_test/
    contact_matter_taxonomy_events.csv
    contact_matter_taxonomy_summary.csv
    contact_matter_taxonomy_by_species.csv
    contact_matter_taxonomy_projection.png
"""

from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.cluster import DBSCAN
from sklearn.decomposition import PCA
from sklearn.metrics import silhouette_score


OUT = Path("results/research_final/contact_matter_taxonomy_test")
OUT.mkdir(parents=True, exist_ok=True)

SEED = 1729
rng = np.random.default_rng(SEED)

N = 128
T_STEPS = 360
NUM_CONFIGS = 72

DBSCAN_EPS = 0.86
DBSCAN_MIN_SAMPLES = 4

EPS = 1e-9

x = np.linspace(-1.0, 1.0, N)
y = np.linspace(-1.0, 1.0, N)
X, Y = np.meshgrid(x, y)


def gaussian_ring(cx, cy, radius, sigma):
    r = np.sqrt((X - cx) ** 2 + (Y - cy) ** 2)
    return np.exp(-((r - radius) ** 2) / (2.0 * sigma**2))


def centers_for_species(t, species_id, num_clusters):
    phase = 2.0 * np.pi * t / T_STEPS

    if species_id == 0:
        base_radius = 0.38 + 0.06 * np.sin(2.0 * phase)
        twist = 0.08 * np.sin(phase)
    elif species_id == 1:
        base_radius = 0.42 + 0.10 * np.sin(2.0 * phase)
        twist = 0.20 * np.sin(phase)
    elif species_id == 2:
        base_radius = 0.34 + 0.04 * np.sin(3.0 * phase)
        twist = 0.32 * np.sin(2.0 * phase)
    elif species_id == 3:
        base_radius = 0.47 + 0.08 * np.sin(phase)
        twist = 0.45 * np.sin(2.0 * phase)
    else:
        base_radius = 0.40 + 0.06 * np.sin(2.0 * phase)
        twist = 0.12 * np.sin(phase)

    centers = []

    for k in range(num_clusters):
        angle = 2.0 * np.pi * k / num_clusters
        angle += twist
        angle += 0.04 * np.sin(phase + k)

        anisotropy = 1.0 + 0.12 * np.sin(species_id + k)

        cx = base_radius * anisotropy * np.cos(angle)
        cy = base_radius / anisotropy * np.sin(angle)

        centers.append([cx, cy])

    return np.asarray(centers)


def mantle_field(t, species_id, num_clusters, waves_per_cluster, perturbation):
    centers = centers_for_species(t, species_id, num_clusters)

    mantles = []
    phase = 2.0 * np.pi * t / T_STEPS

    for cid, (cx, cy) in enumerate(centers):
        cluster = np.zeros((N, N))

        for w in range(waves_per_cluster):
            local_phase = phase + 0.53 * cid + 0.31 * w + 0.17 * species_id

            radius = 0.16 + 0.035 * np.sin((2 + species_id % 3) * local_phase)
            sigma = 0.035 + 0.006 * np.cos(2.0 * local_phase)

            jitter_x = perturbation * rng.normal()
            jitter_y = perturbation * rng.normal()

            cluster += gaussian_ring(
                cx + jitter_x,
                cy + jitter_y,
                radius,
                sigma,
            )

        cluster /= waves_per_cluster
        mantles.append(cluster)

    return np.asarray(mantles)


def bounded_ratio(a, b):
    """
    Bounded contrast ratio in [0, 1].
    Avoids infinite loop/tunnel scores when one channel is near zero.
    """
    return float(a / (a + b + EPS))


def contact_channels(mantles):
    num_clusters = mantles.shape[0]

    pair_sum = np.zeros((N, N))
    pair_strengths = []

    for i in range(num_clusters):
        for j in range(i + 1, num_clusters):
            p = mantles[i] * mantles[j]
            pair_sum += p
            pair_strengths.append(float(p.mean()))

    pair_strengths = np.asarray(pair_strengths)

    r = np.sqrt(X**2 + Y**2)

    central_mask = r < 0.22
    inner_mask = (r >= 0.22) & (r < 0.45)
    outer_mask = (r >= 0.45) & (r < 0.75)

    central = float(pair_sum[central_mask].mean())
    inner = float(pair_sum[inner_mask].mean())
    outer = float(pair_sum[outer_mask].mean())
    total = float(pair_sum.mean())
    peak = float(pair_sum.max())

    threshold = np.quantile(pair_strengths, 0.65) if len(pair_strengths) else 0.0
    strong_pairs = int(np.sum(pair_strengths >= threshold))

    loop_score = bounded_ratio(central, outer)
    tunnel_score = bounded_ratio(inner, central)

    contact_capacity = float(strong_pairs)

    return {
        "total": total,
        "central": central,
        "inner": inner,
        "outer": outer,
        "peak": peak,
        "strong_pairs": strong_pairs,
        "loop_score": loop_score,
        "tunnel_score": tunnel_score,
        "contact_capacity": contact_capacity,
    }


def recurrence_from_spectrum(signal):
    """
    Returns:
        dominant_frequency,
        dominant_period,
        periodicity_score,
        recurrence_corr,
        recurrence_strength,
        phase_orientation,
        intensity_contrast

    recurrence_corr is signed.
    recurrence_strength = abs(recurrence_corr).
    phase_orientation = +1 for in-phase, -1 for anti-phase.
    """
    signal = np.asarray(signal, dtype=float)
    centered = signal - np.mean(signal)

    spectrum = np.abs(np.fft.rfft(centered)) ** 2
    freqs = np.fft.rfftfreq(len(centered), d=1.0)

    total_power = float(spectrum[1:].sum() + EPS)

    if len(spectrum) <= 1 or total_power <= EPS:
        return 0.0, len(signal), 0.0, 0.0, 0.0, 0, 0.0

    dominant_idx = int(np.argmax(spectrum[1:]) + 1)
    dominant_frequency = float(freqs[dominant_idx])
    dominant_power = float(spectrum[dominant_idx])
    periodicity_score = dominant_power / total_power

    if dominant_frequency <= EPS:
        dominant_period = len(signal)
    else:
        dominant_period = int(round(1.0 / dominant_frequency))

    candidate_lags = [
        dominant_period,
        max(1, dominant_period // 2),
        min(len(signal) - 1, 2 * dominant_period),
    ]

    recurrence_values = []

    for lag in candidate_lags:
        if lag <= 0 or lag >= len(signal):
            continue

        a = centered[:-lag]
        b = centered[lag:]

        if np.std(a) <= EPS or np.std(b) <= EPS:
            continue

        corr = float(np.corrcoef(a, b)[0, 1])
        recurrence_values.append(corr)

    if recurrence_values:
        recurrence_corr = max(recurrence_values, key=lambda v: abs(v))
    else:
        recurrence_corr = 0.0

    recurrence_strength = abs(recurrence_corr)

    if recurrence_corr > 0:
        phase_orientation = 1
    elif recurrence_corr < 0:
        phase_orientation = -1
    else:
        phase_orientation = 0

    intensity_contrast = float(
        (np.max(signal) - np.min(signal))
        / (np.mean(np.abs(signal)) + EPS)
    )

    return (
        dominant_frequency,
        dominant_period,
        periodicity_score,
        recurrence_corr,
        recurrence_strength,
        phase_orientation,
        intensity_contrast,
    )


rows = []

for cfg in range(NUM_CONFIGS):
    latent_species = cfg % 4
    num_clusters = 3 + (cfg % 4)
    waves_per_cluster = 3 + (cfg % 3)
    perturbation = 0.003 * (cfg % 5)

    records = []

    for t in range(T_STEPS):
        mantles = mantle_field(
            t,
            latent_species,
            num_clusters,
            waves_per_cluster,
            perturbation,
        )

        ch = contact_channels(mantles)
        ch["time"] = t
        records.append(ch)

    ts = pd.DataFrame(records)

    (
        freq,
        period,
        periodicity,
        recurrence_corr,
        recurrence_strength,
        phase_orientation,
        contrast,
    ) = recurrence_from_spectrum(ts["total"].to_numpy())

    if np.std(ts["central"]) > EPS and np.std(ts["outer"]) > EPS:
        central_peripheral_coupling = float(
            np.corrcoef(ts["central"], ts["outer"])[0, 1]
        )
    else:
        central_peripheral_coupling = 0.0

    rows.append(
        {
            "config_id": cfg,
            "latent_species": latent_species,
            "num_clusters": num_clusters,
            "waves_per_cluster": waves_per_cluster,
            "perturbation": perturbation,
            "dominant_frequency": freq,
            "dominant_period": period,
            "periodicity_score": periodicity,
            "recurrence_corr": recurrence_corr,
            "recurrence_strength": recurrence_strength,
            "phase_orientation": phase_orientation,
            "intensity_contrast": contrast,
            "central_peripheral_coupling": central_peripheral_coupling,
            "mean_loop_score": float(ts["loop_score"].mean()),
            "mean_tunnel_score": float(ts["tunnel_score"].mean()),
            "mean_contact_capacity": float(ts["contact_capacity"].mean()),
            "mean_strong_pairs": float(ts["strong_pairs"].mean()),
            "log_peak_contact_intensity": float(np.log1p(ts["peak"].max())),
            "log_mean_total_contact": float(np.log1p(ts["total"].mean())),
        }
    )


events = pd.DataFrame(rows)

feature_cols = [
    "num_clusters",
    "waves_per_cluster",
    "dominant_frequency",
    "dominant_period",
    "periodicity_score",
    "recurrence_strength",
    "phase_orientation",
    "intensity_contrast",
    "central_peripheral_coupling",
    "mean_loop_score",
    "mean_tunnel_score",
    "mean_contact_capacity",
    "mean_strong_pairs",
    "log_peak_contact_intensity",
    "log_mean_total_contact",
]

features = (
    events[feature_cols]
    .replace([np.inf, -np.inf], np.nan)
    .fillna(0.0)
    .to_numpy()
)

features = (features - features.mean(axis=0)) / (features.std(axis=0) + EPS)

labels = DBSCAN(
    eps=DBSCAN_EPS,
    min_samples=DBSCAN_MIN_SAMPLES,
).fit_predict(features)

events["matter_species"] = labels

valid = labels >= 0
num_species = len(set(labels)) - (1 if -1 in labels else 0)
noise_fraction = float(np.mean(labels == -1))

if num_species >= 2 and np.any(valid):
    sil = float(silhouette_score(features[valid], labels[valid]))
else:
    sil = np.nan

species_rows = []

for label in sorted(set(labels)):
    if label < 0:
        continue

    subset = events[events["matter_species"] == label]

    species_rows.append(
        {
            "matter_species": int(label),
            "count": int(len(subset)),
            "mean_periodicity_score": float(subset["periodicity_score"].mean()),
            "mean_recurrence_corr": float(subset["recurrence_corr"].mean()),
            "mean_recurrence_strength": float(subset["recurrence_strength"].mean()),
            "mean_phase_orientation": float(subset["phase_orientation"].mean()),
            "mean_loop_score": float(subset["mean_loop_score"].mean()),
            "mean_tunnel_score": float(subset["mean_tunnel_score"].mean()),
            "mean_contact_capacity": float(subset["mean_contact_capacity"].mean()),
            "mean_strong_pairs": float(subset["mean_strong_pairs"].mean()),
        }
    )

by_species = pd.DataFrame(species_rows)

mean_periodicity = float(events["periodicity_score"].mean())
mean_recurrence_corr = float(events["recurrence_corr"].mean())
mean_recurrence_strength = float(events["recurrence_strength"].mean())
mean_capacity = float(events["mean_contact_capacity"].mean())

if (
    num_species >= 3
    and noise_fraction <= 0.30
    and mean_periodicity >= 0.35
    and mean_recurrence_strength >= 0.75
    and sil >= 0.65
):
    verdict = "contact_matter_taxonomy_supported"
elif (
    num_species >= 2
    and mean_periodicity >= 0.25
    and mean_recurrence_strength >= 0.60
):
    verdict = "weak_contact_matter_taxonomy"
else:
    verdict = "contact_matter_taxonomy_not_supported"

summary = pd.DataFrame(
    [
        {
            "num_configs": NUM_CONFIGS,
            "num_species": int(num_species),
            "noise_fraction": noise_fraction,
            "silhouette_score": sil,
            "mean_periodicity_score": mean_periodicity,
            "mean_recurrence_corr": mean_recurrence_corr,
            "mean_recurrence_strength": mean_recurrence_strength,
            "mean_contact_capacity": mean_capacity,
            "verdict": verdict,
        }
    ]
)

events.to_csv(OUT / "contact_matter_taxonomy_events.csv", index=False)
summary.to_csv(OUT / "contact_matter_taxonomy_summary.csv", index=False)
by_species.to_csv(OUT / "contact_matter_taxonomy_by_species.csv", index=False)

proj = PCA(n_components=2).fit_transform(features)

plt.figure(figsize=(7, 6))
plt.scatter(proj[:, 0], proj[:, 1], c=labels, s=28)
plt.title("BST contact-matter taxonomy")
plt.xlabel("PC1")
plt.ylabel("PC2")
plt.tight_layout()
plt.savefig(OUT / "contact_matter_taxonomy_projection.png", dpi=220)
plt.close()

print("\n=== BST CONTACT-MATTER TAXONOMY TEST ===\n")
print(summary.to_string(index=False))

print("\nSpecies summary:")
if len(by_species):
    print(by_species.to_string(index=False))
else:
    print("(no stable species detected)")

print(f"\n[OK] wrote {OUT / 'contact_matter_taxonomy_events.csv'}")
print(f"[OK] wrote {OUT / 'contact_matter_taxonomy_summary.csv'}")
print(f"[OK] wrote {OUT / 'contact_matter_taxonomy_by_species.csv'}")
print(f"[OK] wrote {OUT / 'contact_matter_taxonomy_projection.png'}")
print("[DONE] contact-matter taxonomy test complete")