#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
BST — Emergent Geodesics Test
=============================

Purpose
-------
Test whether trajectories generated by an effective BST closure geometry
are approximated by geodesic-like paths of the induced metric.

This experiment is conservative: it does not claim full GR geodesics.
It tests whether closure-induced geometry captures the observed trajectory
class with bounded normalized error.

Outputs
-------
results/research_final/emergent_geodesics_test/
    emergent_geodesics_summary.csv
    emergent_geodesics_timeseries.csv
    emergent_geodesics_paths.png
    emergent_geodesics_error.png
"""

from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


OUT = Path("results/research_final/emergent_geodesics_test")
OUT.mkdir(parents=True, exist_ok=True)

NX = 180
NY = 180
DX = 1.0
DT = 0.05
N_STEPS = 500

ALPHA = 1.4
FORCE_GAIN = 0.15
DAMP = 0.999
EPS = 1e-12


def gaussian(cx, cy, sigma, amp=1.0):
    y, x = np.indices((NY, NX))
    r2 = (x - cx) ** 2 + (y - cy) ** 2
    return amp * np.exp(-r2 / (2.0 * sigma**2))


def normalize(x):
    mn = float(np.min(x))
    mx = float(np.max(x))
    return (x - mn) / (mx - mn + EPS)


def grad(f):
    gy, gx = np.gradient(f, DX, DX)
    return gx, gy


def bilinear(arr, pos):
    x = float(np.clip(pos[0], 0, NX - 1.001))
    y = float(np.clip(pos[1], 0, NY - 1.001))

    x0 = int(np.floor(x))
    y0 = int(np.floor(y))
    x1 = min(x0 + 1, NX - 1)
    y1 = min(y0 + 1, NY - 1)

    tx = x - x0
    ty = y - y0

    return (
        (1 - tx) * (1 - ty) * arr[y0, x0]
        + tx * (1 - ty) * arr[y0, x1]
        + (1 - tx) * ty * arr[y1, x0]
        + tx * ty * arr[y1, x1]
    )


def sample_vec(gx, gy, pos):
    return np.array(
        [
            bilinear(gx, pos),
            bilinear(gy, pos),
        ],
        dtype=float,
    )


def make_closure_metric():
    """
    Closure-supported effective metric proxy.

    rho represents structured closure density.
    n = 1 + alpha*rho is an optical/conformal index proxy.
    """
    rho = (
        gaussian(70, 95, 18, 1.00)
        + gaussian(115, 75, 22, 0.75)
        + 0.25 * gaussian(95, 125, 32, 1.00)
    )

    rho_n = normalize(rho)
    n = 1.0 + ALPHA * rho_n
    return rho_n, n


def integrate_bst_trajectory(n, start, vel0):
    """
    Effective BST trajectory.

    The particle is advected by the closure-gradient field.
    """
    gx, gy = grad(np.log(n + EPS))

    pos = start.copy()
    vel = vel0.copy()
    traj = []

    for _ in range(N_STEPS):
        acc = FORCE_GAIN * sample_vec(gx, gy, pos)
        vel = DAMP * vel + DT * acc
        pos = pos + DT * vel

        pos[0] = np.clip(pos[0], 2, NX - 3)
        pos[1] = np.clip(pos[1], 2, NY - 3)

        traj.append(pos.copy())

    return np.array(traj)


def integrate_geodesic_proxy(n, start, vel0):
    """
    Weak conformal-geodesic proxy.

    Acceleration is the transverse component of grad(log n), preserving
    the affine speed scale.
    """
    gx, gy = grad(np.log(n + EPS))

    pos = start.copy()
    vel = vel0.copy()
    traj = []

    speed0 = np.linalg.norm(vel0) + EPS

    for _ in range(N_STEPS):
        g = sample_vec(gx, gy, pos)

        vhat = vel / (np.linalg.norm(vel) + EPS)
        transverse_g = g - np.dot(g, vhat) * vhat

        acc = FORCE_GAIN * transverse_g
        vel = vel + DT * acc
        vel = speed0 * vel / (np.linalg.norm(vel) + EPS)

        pos = pos + DT * vel

        pos[0] = np.clip(pos[0], 2, NX - 3)
        pos[1] = np.clip(pos[1], 2, NY - 3)

        traj.append(pos.copy())

    return np.array(traj)


def trajectory_diagnostics(sim, geo):
    dist = np.linalg.norm(sim - geo, axis=1)
    path_len = np.cumsum(
        np.r_[0.0, np.linalg.norm(np.diff(sim, axis=0), axis=1)]
    )
    norm_error = dist / (path_len + 1.0)
    return dist, path_len, norm_error


def classify(mean_norm_error, final_norm_error):
    if mean_norm_error < 0.10 and final_norm_error < 0.20:
        return "strong_geodesic_recovery"
    if mean_norm_error < 0.15 and final_norm_error < 0.30:
        return "moderate_geodesic_recovery"
    if mean_norm_error < 0.25:
        return "weak_geodesic_recovery"
    return "no_geodesic_recovery"


def main():
    print("\n=== BST EMERGENT GEODESICS TEST ===")

    rho, n = make_closure_metric()

    start = np.array([25.0, 130.0])
    vel0 = np.array([0.65, -0.22])

    sim = integrate_bst_trajectory(n, start, vel0)
    geo = integrate_geodesic_proxy(n, start, vel0)

    dist, path_len, norm_error = trajectory_diagnostics(sim, geo)

    timeseries = pd.DataFrame({
        "step": np.arange(N_STEPS),
        "time": np.arange(N_STEPS) * DT,
        "sim_x": sim[:, 0],
        "sim_y": sim[:, 1],
        "geo_x": geo[:, 0],
        "geo_y": geo[:, 1],
        "trajectory_error": dist,
        "path_length": path_len,
        "normalized_error": norm_error,
    })

    mean_norm_error = float(np.mean(norm_error))
    final_norm_error = float(norm_error[-1])
    max_norm_error = float(np.max(norm_error))
    verdict = classify(mean_norm_error, final_norm_error)

    summary = pd.DataFrame([{
        "mean_error": float(np.mean(dist)),
        "final_error": float(dist[-1]),
        "max_error": float(np.max(dist)),
        "mean_normalized_error": mean_norm_error,
        "final_normalized_error": final_norm_error,
        "max_normalized_error": max_norm_error,
        "verdict": verdict,
    }])

    timeseries_path = OUT / "emergent_geodesics_timeseries.csv"
    summary_path = OUT / "emergent_geodesics_summary.csv"

    timeseries.to_csv(timeseries_path, index=False)
    summary.to_csv(summary_path, index=False)

    plt.figure(figsize=(7, 7))
    plt.imshow(n, origin="lower")
    plt.plot(sim[:, 0], sim[:, 1], label="BST trajectory")
    plt.plot(geo[:, 0], geo[:, 1], "--", label="geodesic proxy")
    plt.scatter([start[0]], [start[1]], s=60, label="start")
    plt.legend()
    plt.title("Emergent geodesic comparison")
    plt.xticks([])
    plt.yticks([])
    plt.tight_layout()
    plt.savefig(OUT / "emergent_geodesics_paths.png", dpi=220)
    plt.close()

    plt.figure(figsize=(9, 4))
    plt.plot(timeseries["time"], timeseries["trajectory_error"], label="absolute error")
    plt.plot(timeseries["time"], timeseries["normalized_error"], label="normalized error")
    plt.legend()
    plt.xlabel("time")
    plt.ylabel("error")
    plt.title("Trajectory vs geodesic proxy error")
    plt.tight_layout()
    plt.savefig(OUT / "emergent_geodesics_error.png", dpi=220)
    plt.close()

    print(summary.to_string(index=False))
    print(f"\n[OK] wrote {timeseries_path}")
    print(f"[OK] wrote {summary_path}")
    print(f"[OK] wrote {OUT / 'emergent_geodesics_paths.png'}")
    print(f"[OK] wrote {OUT / 'emergent_geodesics_error.png'}")
    print("[DONE] emergent geodesics test complete")


if __name__ == "__main__":
    main()