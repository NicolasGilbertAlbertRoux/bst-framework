#!/usr/bin/env python3
# -*- coding: utf-8 -*-

"""
BST — Stable Wave-Cluster Taxonomy Test

Purpose
-------
Classify stable primordial wave-cluster configurations before scanning
higher-order contact matter structures.

This test searches for the preferred stable wave aggregates generated by
saturation, recurrence, and perturbation robustness.

Outputs
-------
results/research_final/wave_cluster_taxonomy_test/
    wave_cluster_taxonomy_events.csv
    wave_cluster_taxonomy_summary.csv
    wave_cluster_taxonomy_projection.png
"""

from pathlib import Path
from collections import deque
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.cluster import DBSCAN
from sklearn.decomposition import PCA
from sklearn.metrics import silhouette_score


OUT = Path("results/research_final/wave_cluster_taxonomy_test")
OUT.mkdir(parents=True, exist_ok=True)

SEED = 1729
rng = np.random.default_rng(SEED)

N = 128
T_STEPS = 160
NUM_WAVES = 9

MIN_CLUSTER_AREA = 24
DBSCAN_EPS = 0.58
DBSCAN_MIN_SAMPLES = 10

PERTURBATION_LEVELS = [0.0, 0.015, 0.03, 0.06, 0.09]

x = np.linspace(-1.0, 1.0, N)
y = np.linspace(-1.0, 1.0, N)
X, Y = np.meshgrid(x, y)


def connected_components(mask):
    visited = np.zeros_like(mask, dtype=bool)
    comps = []
    h, w = mask.shape

    for iy in range(h):
        for ix in range(w):
            if not mask[iy, ix] or visited[iy, ix]:
                continue

            q = deque([(iy, ix)])
            visited[iy, ix] = True
            pts = []

            while q:
                cy, cx = q.popleft()
                pts.append((cy, cx))

                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    ny, nx = cy + dy, cx + dx
                    if (
                        0 <= ny < h
                        and 0 <= nx < w
                        and mask[ny, nx]
                        and not visited[ny, nx]
                    ):
                        visited[ny, nx] = True
                        q.append((ny, nx))

            comps.append(np.asarray(pts, dtype=int))

    return comps


def perimeter(mask, pts):
    h, w = mask.shape
    p = 0

    for cy, cx in pts:
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            ny, nx = cy + dy, cx + dx
            if ny < 0 or ny >= h or nx < 0 or nx >= w or not mask[ny, nx]:
                p += 1

    return p


def wave_mantles(t, perturbation=0.0):
    local_rng = np.random.default_rng(
        SEED + int(1000 * perturbation) + 31 * t
    )

    mantles = []

    for i in range(NUM_WAVES):
        angle = 2 * np.pi * i / NUM_WAVES

        radial_jitter = perturbation * local_rng.normal()
        angular_jitter = perturbation * local_rng.normal()

        cx = (0.42 + radial_jitter) * np.cos(angle + 0.011 * t + angular_jitter)
        cy = (0.42 + radial_jitter) * np.sin(angle + 0.013 * t + angular_jitter)

        r = np.sqrt((X - cx) ** 2 + (Y - cy) ** 2)

        radius = 0.28 + 0.05 * np.sin(0.07 * t + 0.8 * i)
        sigma = 0.045 + 0.006 * np.cos(0.04 * t + i)

        mantle = np.exp(-((r - radius) ** 2) / (2 * sigma**2))
        mantles.append(mantle)

    return np.stack(mantles, axis=0)


def extract_clusters(perturbation):
    rows = []

    for t in range(T_STEPS):
        mantles = wave_mantles(t, perturbation)

        density = mantles.sum(axis=0)
        overlap = np.sum(mantles > 0.32, axis=0)

        # Saturation: enough overlapping mantles, but not arbitrary density.
        saturated = (overlap >= 2) & (density >= np.quantile(density, 0.72))

        comps = connected_components(saturated)

        for comp_id, pts in enumerate(comps):
            area = len(pts)

            if area < MIN_CLUSTER_AREA:
                continue

            ys, xs = pts[:, 0], pts[:, 1]
            p = perimeter(saturated, pts)

            compactness = 4 * np.pi * area / ((p + 1e-9) ** 2)
            mean_density = float(density[ys, xs].mean())
            max_density = float(density[ys, xs].max())
            mean_overlap = float(overlap[ys, xs].mean())
            contact_capacity = float(np.mean(overlap[ys, xs] * density[ys, xs]))

            cx = float(xs.mean() / N)
            cy = float(ys.mean() / N)

            rows.append(
                {
                    "perturbation": perturbation,
                    "time": t,
                    "component_id": comp_id,
                    "area": area,
                    "perimeter": p,
                    "compactness": compactness,
                    "mean_density": mean_density,
                    "max_density": max_density,
                    "mean_overlap": mean_overlap,
                    "contact_capacity": contact_capacity,
                    "centroid_x": cx,
                    "centroid_y": cy,
                }
            )

    return pd.DataFrame(rows)


def feature_matrix(df):
    cols = [
        "area",
        "perimeter",
        "compactness",
        "mean_density",
        "max_density",
        "mean_overlap",
        "contact_capacity",
    ]

    Xf = df[cols].to_numpy(dtype=float)
    return (Xf - Xf.mean(axis=0)) / (Xf.std(axis=0) + 1e-9)


def classify(df):
    if len(df) < 20:
        return np.full(len(df), -1), 0, np.nan

    Xf = feature_matrix(df)

    labels = DBSCAN(
        eps=DBSCAN_EPS,
        min_samples=DBSCAN_MIN_SAMPLES,
    ).fit_predict(Xf)

    valid = labels >= 0
    num_classes = len(set(labels)) - (1 if -1 in labels else 0)

    if num_classes >= 2:
        sil = float(silhouette_score(Xf[valid], labels[valid]))
    else:
        sil = np.nan

    return labels, num_classes, sil


def persistence(df, labels):
    vals = []

    for label in sorted(set(labels)):
        if label < 0:
            continue

        times = df.loc[labels == label, "time"]
        vals.append(len(set(times)) / T_STEPS)

    return float(np.mean(vals)) if vals else np.nan


def main():
    print("\n=== BST STABLE WAVE-CLUSTER TAXONOMY TEST ===")

    all_rows = []
    summaries = []

    for p in PERTURBATION_LEVELS:
        df = extract_clusters(p)

        if len(df) == 0:
            summaries.append(
                {
                    "perturbation": p,
                    "num_events": 0,
                    "num_classes": 0,
                    "noise_fraction": np.nan,
                    "silhouette_score": np.nan,
                    "mean_persistence": np.nan,
                    "mean_contact_capacity": np.nan,
                }
            )
            continue

        labels, num_classes, sil = classify(df)
        df["cluster_class"] = labels

        valid = labels >= 0

        summaries.append(
            {
                "perturbation": p,
                "num_events": int(len(df)),
                "num_classes": int(num_classes),
                "noise_fraction": float(np.mean(labels == -1)),
                "silhouette_score": sil,
                "mean_persistence": persistence(df, labels),
                "mean_contact_capacity": float(
                    df.loc[valid, "contact_capacity"].mean()
                    if np.any(valid)
                    else np.nan
                ),
            }
        )

        all_rows.append(df)

    events = pd.concat(all_rows, ignore_index=True)
    by_perturbation = pd.DataFrame(summaries)

    robust = by_perturbation[by_perturbation["perturbation"] > 0]

    mean_classes = float(robust["num_classes"].mean())
    mean_persistence = float(robust["mean_persistence"].mean())
    mean_capacity = float(robust["mean_contact_capacity"].mean())
    mean_noise = float(robust["noise_fraction"].mean())

    if mean_classes >= 2 and mean_persistence >= 0.35 and mean_capacity > 1.0:
        verdict = "stable_wave_cluster_taxonomy_supported"
    elif mean_classes >= 1 and mean_persistence >= 0.20:
        verdict = "weak_wave_cluster_taxonomy"
    else:
        verdict = "no_stable_wave_cluster_taxonomy"

    summary = pd.DataFrame(
        [
            {
                "mean_classes_under_perturbation": mean_classes,
                "mean_persistence_under_perturbation": mean_persistence,
                "mean_contact_capacity": mean_capacity,
                "mean_noise_fraction": mean_noise,
                "verdict": verdict,
            }
        ]
    )

    events.to_csv(OUT / "wave_cluster_taxonomy_events.csv", index=False)
    by_perturbation.to_csv(
        OUT / "wave_cluster_taxonomy_by_perturbation.csv",
        index=False,
    )
    summary.to_csv(OUT / "wave_cluster_taxonomy_summary.csv", index=False)

    Xf = feature_matrix(events)
    proj = PCA(n_components=2).fit_transform(Xf)

    plt.figure(figsize=(7, 6))
    plt.scatter(proj[:, 0], proj[:, 1], c=events["cluster_class"], s=10)
    plt.title("Stable wave-cluster taxonomy")
    plt.xlabel("PC1")
    plt.ylabel("PC2")
    plt.tight_layout()
    plt.savefig(OUT / "wave_cluster_taxonomy_projection.png", dpi=220)
    plt.close()

    print("\nPerturbation diagnostics:")
    print(by_perturbation.to_string(index=False))

    print("\nGlobal summary:")
    print(summary.to_string(index=False))

    print(f"\n[OK] wrote {OUT / 'wave_cluster_taxonomy_events.csv'}")
    print(f"[OK] wrote {OUT / 'wave_cluster_taxonomy_by_perturbation.csv'}")
    print(f"[OK] wrote {OUT / 'wave_cluster_taxonomy_summary.csv'}")
    print(f"[OK] wrote {OUT / 'wave_cluster_taxonomy_projection.png'}")
    print("[DONE] stable wave-cluster taxonomy test complete")


if __name__ == "__main__":
    main()