#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
BST / OMM-SBT — String Mode Tracker
===================================

Purpose
-------
Track a flexible closed loop generated by complex wave-cluster intersections
through beating phase and measure whether its modal dynamics resemble a
stable closed-loop/string-like spectrum.

This script tests:
    - R(theta,t) worldsheet-like observable,
    - angular modes n,
    - temporal frequencies omega_n,
    - dispersion relation omega_n ~ n^alpha,
    - modal persistence,
    - mode coupling / energy transfer.

It does NOT claim:
    - derivation of string theory,
    - derivation of M-theory,
    - Polyakov/Nambu-Goto equivalence,
    - Virasoro constraints.

Run:
    python bst_string_mode_tracker.py --fast

Outputs:
    results/research_final/bst_string_mode_tracker/
"""

from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

OUTDIR = Path("results/research_final/bst_string_mode_tracker")


def log(s):
    print(s, flush=True)


def make_grid(n=55, lim=4.5):
    a = np.linspace(-lim, lim, n)
    return np.meshgrid(a, a, a, indexing="ij")


def cluster_field(X, Y, Z, center, phase, k0, sigma, complexity, seed):
    rng = np.random.default_rng(seed)
    cx, cy, cz = center
    F = np.zeros_like(X)

    for j in range(complexity):
        off = rng.normal(0, 0.33, 3)
        amp = rng.uniform(0.45, 1.0)
        kj = k0 * rng.uniform(0.65, 1.45)
        sig = sigma * rng.uniform(0.70, 1.35)
        ph = phase * rng.uniform(0.6, 1.4) + rng.uniform(0, 2*np.pi)

        ax, ay, az = rng.uniform(0.65, 1.45, 3)
        x = (X - (cx + off[0])) * ax
        y = (Y - (cy + off[1])) * ay
        z = (Z - (cz + off[2])) * az
        R = np.sqrt(x*x + y*y + z*z)

        F += amp * np.exp(-(R**2)/(2*sig**2)) * np.cos(kj*R + ph)

    return F / max(complexity, 1)


def intersection_points(F1, F2, X, Y, Z, threshold, tol):
    mask = (np.abs(F1-threshold) < tol) & (np.abs(F2-threshold) < tol)
    return np.column_stack([X[mask], Y[mask], Z[mask]])


def angular_profile(points, bins=96):
    if len(points) < 80:
        return None

    C = points.mean(axis=0)
    P = points - C
    cov = np.cov(P.T)
    vals, vecs = np.linalg.eigh(cov)
    order = np.argsort(vals)[::-1]
    vecs = vecs[:, order]

    a = P @ vecs[:, 0]
    b = P @ vecs[:, 1]
    h = P @ vecs[:, 2]

    r = np.sqrt(a*a + b*b)
    th = np.arctan2(b, a)
    edges = np.linspace(-np.pi, np.pi, bins+1)

    rb = np.full(bins, np.nan)
    counts = np.zeros(bins)
    for i in range(bins):
        m = (th >= edges[i]) & (th < edges[i+1])
        counts[i] = np.sum(m)
        if np.any(m):
            rb[i] = np.median(r[m])

    coverage = np.count_nonzero(counts) / bins
    if coverage < 0.35:
        return None

    idx = np.arange(bins)
    good = ~np.isnan(rb)
    rb2 = np.interp(idx, np.r_[idx[good], idx[good]+bins], np.r_[rb[good], rb[good]])

    mean_r = np.mean(rb2)
    radius_cv = np.std(rb2) / (mean_r + 1e-12)
    plane_thickness = np.std(h) / (mean_r + 1e-12)
    loop_score = coverage * (1/(1+radius_cv)) * (1/(1+plane_thickness)) * np.tanh(mean_r/0.25)

    return rb2, dict(
        n_points=int(len(points)),
        coverage=float(coverage),
        mean_radius=float(mean_r),
        radius_cv=float(radius_cv),
        plane_thickness=float(plane_thickness),
        loop_score=float(loop_score),
    )


def build_R_theta_t(params, steps=80, bins=96, grid_n=55):
    X, Y, Z = make_grid(n=grid_n, lim=4.5)
    profiles = []
    metrics = []

    for t_idx, ph in enumerate(np.linspace(0, 2*np.pi, steps, endpoint=False)):
        F1 = cluster_field(X, Y, Z, (-params["sep"]/2,0,0), ph, params["k"], params["sigma"], params["complexity"], 100+params["seed"])
        F2 = cluster_field(X, Y, Z, ( params["sep"]/2,0,0), -ph, params["k"], params["sigma"], params["complexity"], 200+params["seed"])
        scale = max(np.std(F1), np.std(F2), 1e-9)
        pts = intersection_points(F1, F2, X, Y, Z, params["threshold"], 0.055*scale)
        prof = angular_profile(pts, bins=bins)

        if prof is None:
            profiles.append(np.full(bins, np.nan))
            metrics.append(dict(t_idx=t_idx, phase=float(ph), valid=False, loop_score=0))
        else:
            rb, m = prof
            profiles.append(rb)
            metrics.append(dict(t_idx=t_idx, phase=float(ph), valid=True, **m))

    R = np.array(profiles)
    mdf = pd.DataFrame(metrics)

    # Fill invalid rows by interpolation if not too many.
    valid = np.all(np.isfinite(R), axis=1)
    if np.sum(valid) >= max(8, steps//4):
        for j in range(R.shape[1]):
            idx = np.arange(R.shape[0])
            good = np.isfinite(R[:, j])
            R[:, j] = np.interp(idx, idx[good], R[good, j])
    return R, mdf


def modal_analysis(R, max_mode=20):
    # Remove mean radius per time.
    R0 = R - np.nanmean(R, axis=1, keepdims=True)

    # Angular Fourier modes over theta.
    A = np.fft.rfft(R0, axis=1)
    mode_rows = []

    for n in range(1, min(max_mode+1, A.shape[1])):
        amp_t = np.abs(A[:, n])
        phase_t = np.unwrap(np.angle(A[:, n]))

        # Temporal spectrum of mode amplitude.
        amp_centered = amp_t - np.mean(amp_t)
        temporal_spec = np.abs(np.fft.rfft(amp_centered))
        if len(temporal_spec) > 1:
            omega_idx = int(np.argmax(temporal_spec[1:]) + 1)
            omega_power = float(temporal_spec[omega_idx] / (np.sum(temporal_spec) + 1e-12))
        else:
            omega_idx = 0
            omega_power = 0.0

        persistence = float(np.mean(amp_t) / (np.std(amp_t) + 1e-12))
        energy = float(np.mean(amp_t**2))

        mode_rows.append(dict(
            mode_n=n,
            omega_index=omega_idx,
            omega_power=omega_power,
            mean_amplitude=float(np.mean(amp_t)),
            amplitude_std=float(np.std(amp_t)),
            persistence=persistence,
            modal_energy=energy,
        ))

    df = pd.DataFrame(mode_rows)

    # Fit omega ~ n^alpha on modes with meaningful temporal peaks.
    fit = dict(alpha=np.nan, intercept=np.nan, r2=np.nan, n_fit=0)
    sub = df[(df["omega_index"] > 0) & (df["omega_power"] > 0.08)]
    if len(sub) >= 4:
        x = np.log(sub["mode_n"].to_numpy(float))
        y = np.log(sub["omega_index"].to_numpy(float))
        Afit = np.vstack([x, np.ones_like(x)]).T
        alpha, intercept = np.linalg.lstsq(Afit, y, rcond=None)[0]
        pred = alpha*x + intercept
        ss_res = np.sum((y-pred)**2)
        ss_tot = np.sum((y-y.mean())**2) + 1e-12
        fit = dict(alpha=float(alpha), intercept=float(intercept), r2=float(1-ss_res/ss_tot), n_fit=int(len(sub)))

    return df, fit


def scan_cases(fast=False):
    # Reuse parameter region from previous complex-loop test, but smaller.
    complexities = [2, 3, 5] if fast else [2, 3, 5, 8]
    seps = np.linspace(1.0, 3.6, 4 if fast else 7)
    ks = [1.8, 2.6, 3.4] if fast else [1.6, 2.2, 2.8, 3.4, 4.0]
    sigmas = [1.7, 2.3] if fast else [1.4, 1.8, 2.2, 2.8]
    thresholds = np.linspace(-0.22, 0.32, 4 if fast else 7)

    rows = []
    best = None
    total = len(complexities)*len(seps)*len(ks)*len(sigmas)*len(thresholds)
    done = 0

    for comp in complexities:
        for sep in seps:
            for k in ks:
                for sigma in sigmas:
                    for th in thresholds:
                        seed = 777 + done
                        params = dict(complexity=comp, sep=float(sep), k=float(k), sigma=float(sigma), threshold=float(th), seed=seed)
                        R, mdf = build_R_theta_t(params, steps=32 if fast else 64, bins=72 if fast else 96, grid_n=45 if fast else 55)
                        valid_fraction = float(mdf["valid"].mean())
                        avg_loop_score = float(mdf["loop_score"].mean())

                        if valid_fraction < 0.4:
                            row = dict(**params, valid_fraction=valid_fraction, avg_loop_score=avg_loop_score,
                                       alpha=np.nan, dispersion_r2=np.nan, n_fit=0,
                                       stable_string_mode_score=0.0)
                        else:
                            modes, fit = modal_analysis(R, max_mode=18)
                            modal_persistence = float(np.nanmean(np.clip(modes["persistence"], 0, 10))/10)
                            omega_strength = float(np.nanmean(modes["omega_power"]))
                            dispersion_quality = 0 if np.isnan(fit["r2"]) else max(0, fit["r2"])
                            alpha_reasonable = 0 if np.isnan(fit["alpha"]) else float(np.exp(-((fit["alpha"]-1.0)**2)/(2*0.55**2)))

                            score = (
                                0.25*valid_fraction +
                                0.25*avg_loop_score +
                                0.20*omega_strength +
                                0.20*dispersion_quality +
                                0.10*alpha_reasonable
                            )

                            row = dict(**params, valid_fraction=valid_fraction, avg_loop_score=avg_loop_score,
                                       alpha=fit["alpha"], dispersion_r2=fit["r2"], n_fit=fit["n_fit"],
                                       omega_strength=omega_strength,
                                       modal_persistence=modal_persistence,
                                       alpha_reasonable=alpha_reasonable,
                                       stable_string_mode_score=float(score))

                            if best is None or row["stable_string_mode_score"] > best["row"]["stable_string_mode_score"]:
                                best = dict(row=row, R=R, metrics=mdf, modes=modes, fit=fit, params=params)

                        rows.append(row)
                        done += 1
                        if done % 50 == 0:
                            log(f"[SCAN] {done}/{total} cases")

    df = pd.DataFrame(rows).sort_values("stable_string_mode_score", ascending=False)
    return df, best


def plot_best(best):
    R = best["R"]
    modes = best["modes"]
    row = best["row"]

    fig, ax = plt.subplots(figsize=(8,4))
    im = ax.imshow(R, aspect="auto", origin="lower")
    fig.colorbar(im, ax=ax, label="R(theta,t)")
    ax.set_title("Worldsheet-like radius observable R(theta,t)")
    ax.set_xlabel("theta bin")
    ax.set_ylabel("beating phase step")
    fig.tight_layout()
    fig.savefig(OUTDIR/"best_R_theta_t.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(7,4))
    ax.scatter(modes["mode_n"], modes["omega_index"], s=50)
    if not np.isnan(row["alpha"]):
        n = np.linspace(max(1, modes["mode_n"].min()), modes["mode_n"].max(), 100)
        c = np.exp(row.get("intercept", 0)) if "intercept" in row else 1
        # Use simple visual proportional fit from data scale.
        sub = modes[(modes["omega_index"] > 0) & (modes["omega_power"] > 0.08)]
        if len(sub) >= 4:
            c = np.exp(np.mean(np.log(sub["omega_index"]) - row["alpha"]*np.log(sub["mode_n"])))
            ax.plot(n, c*(n**row["alpha"]), linestyle="--")
    ax.set_title("Dispersion scan: temporal frequency vs angular mode")
    ax.set_xlabel("angular mode n")
    ax.set_ylabel("dominant temporal frequency index")
    fig.tight_layout()
    fig.savefig(OUTDIR/"best_dispersion_relation.png", dpi=180)
    plt.close(fig)

    fig, ax = plt.subplots(figsize=(8,4))
    ax.bar(modes["mode_n"], modes["modal_energy"])
    ax.set_title("Modal energy distribution")
    ax.set_xlabel("mode n")
    ax.set_ylabel("mean modal energy")
    fig.tight_layout()
    fig.savefig(OUTDIR/"best_modal_energy_distribution.png", dpi=180)
    plt.close(fig)

    best["metrics"].to_csv(OUTDIR/"best_loop_time_metrics.csv", index=False)
    best["modes"].to_csv(OUTDIR/"best_mode_tracker.csv", index=False)


def classify(row):
    if row["stable_string_mode_score"] >= 0.72 and row.get("dispersion_r2", 0) >= 0.5:
        return "strong stable modal string-like signal"
    if row["stable_string_mode_score"] >= 0.55:
        return "moderate stable modal string-like signal"
    if row["valid_fraction"] >= 0.5 and row["avg_loop_score"] >= 0.45:
        return "closed loop dynamics without stable string dispersion"
    return "weak or unsupported"


def write_summary(df, best):
    b = df.iloc[0]
    classification = classify(b)
    text = f"""# BST String Mode Tracker

Best case classification: **{classification}**

Best case:
- stable_string_mode_score: {b['stable_string_mode_score']:.4f}
- valid_fraction: {b['valid_fraction']:.4f}
- avg_loop_score: {b['avg_loop_score']:.4f}
- omega_strength: {b.get('omega_strength', np.nan)}
- modal_persistence: {b.get('modal_persistence', np.nan)}
- dispersion alpha: {b['alpha']}
- dispersion R2: {b['dispersion_r2']}
- n_fit: {int(b['n_fit'])}
- complexity: {int(b['complexity'])}
- sep: {b['sep']:.4f}
- k: {b['k']:.4f}
- sigma: {b['sigma']:.4f}
- threshold: {b['threshold']:.4f}

Interpretation:
- This is the first test aimed at actual modal dynamics R(theta,t), not just geometry.
- A moderate/strong result supports the presence of persistent loop modes.
- A strong string-theory comparison would require stable dispersion, constraints, and an action principle.
- No Polyakov/Nambu-Goto/Virasoro derivation is claimed here.
"""
    (OUTDIR/"summary.md").write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true")
    args = ap.parse_args()

    OUTDIR.mkdir(parents=True, exist_ok=True)
    log("=== BST STRING MODE TRACKER ===")
    log(f"[OUT] {OUTDIR}")

    df, best = scan_cases(fast=args.fast)
    df.to_csv(OUTDIR/"string_mode_tracker_scores.csv", index=False)

    if best is not None:
        plot_best(best)
    write_summary(df, best)

    b = df.iloc[0]
    log(f"[BEST] score={b['stable_string_mode_score']:.4f}, alpha={b['alpha']}, R2={b['dispersion_r2']}, class={classify(b)}")
    log("[DONE]")


if __name__ == "__main__":
    main()
